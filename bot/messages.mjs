// Уведомление Екатерине о заявке.
export function leadNotice({ name, username, service, note }) {
  const who = username ? `@${username}` : 'без имени пользователя — ответьте на это сообщение, бот передаст';
  return `🔥 <b>Новая заявка</b>
${name} — ${who}
Направление: ${service}${note ? `\nСообщение: ${note}` : ''}`;
}

