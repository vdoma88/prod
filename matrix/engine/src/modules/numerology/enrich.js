const I = require('./interpretations')
const { personalYearOf, rodCycleOf } = require('./explain')
const AUTHOR = require('./data/author_matrix.json')

function enrich(result) {
  const c = result.counts
  const nums = result.workingNumbers
  // ── Значения цифр и две задачи — тексты автора методики ──
  // Полностью, без сокращений: data/author_matrix.json снят с калькулятора
  // автора. Раньше здесь были пересказы, разбитые по полу, а пол клиента
  // нигде не хранился — и мужчинам выдавался женский вариант. У автора
  // мужская и женская части — внутри одного текста.
  const digitMeanings = {}
  const keys = result.matrixKeys || {}
  for (let i = 1; i <= 9; i++) {
    digitMeanings[i] = {
      key: keys[i] || null,
      count: c[i] || 0,
      intro: AUTHOR.digitIntro[i] || '',
      text: (keys[i] && AUTHOR.matrix[keys[i]]) || '',
    }
  }
  const task = (n) => (n === undefined || n === null ? null : { number: n, text: AUTHOR.tasks[n] || '' })
  const soulTask = task(result.tasks?.soul)
  const rodTask = task(result.tasks?.rod)

  const pathNum = result.pathNumber
  const birthMeaning = I.BIRTH_MEANINGS[result.birthNumber] || ''

  // ── Column levels (FULL text) ──────
  const colLevels = {
    c123: ['1-4 цифр: ⚠ Заниженная самооценка. Человек себя уничижает: «я так себе», «извините, что родился». Важно постоянно доказывать себе «я молодец», «я классный», «всё могу». Нуждается в словесной поддержке и одобрении. Чем меньше цифр — тем чаще человек себя принижает.',
           '5-7 цифр: ✅ Норма, адекватное восприятие. Человек адекватен в восприятии себя и мира, мир воспринимает его тоже адекватно. Идеальный диапазон — здоровая самооценка.',
           '8+ цифр: ⚠ Перегруз, завышенная самооценка. Чем больше цифр, тем большего мнения о себе человек. Важно отпускаться с небес на землю.'],
    c456: ['0 цифр: 🔴 Пустой канал — программа тотальной нищеты. Человек не может получить достаточную сумму и удержать. При работе с родом канал можно заполнить, но деньги зарабатываются очень тяжело.',
           '1 цифра: ⚠ Слабый, неритмичный канал. Большая амплитуда: нужно много усилий. Трудоголизм, точка входа через единственную цифру (6=труд, 4=тело, 5=социум).',
           '2 цифры: 🟡 Устойчивая конструкция, средние возможности. Больших потерь нет, но и больших доходов. Хорошо когда цифры в разных квадрантах — две точки входа.',
           '3 цифры: 🟡 Неустойчивый канал с амплитудой: заработал — потерял. Правило 3 цифр: заставляет развивать то, чего не хватает. Программа «Деньги = жизнь, деньги = смерть».',
           '4 цифры: ✅ Идеальный канал, суперустойчивая конструкция, донор финансов. Если в каждой клетке по цифре — супер устойчиво. С таким человеком стоит дружить.',
           '5+ цифр: ⚠ Перегруз. Пять цифр = отнимаем 4 → пустой. Шесть = отнимаем 5. Неустойчивый.'],
    c789: ['0-3 цифры: 🔷 Нужен наставник. Если нет любой цифры — талант можно почувствовать через других людей. Обязательно нужен помощник, который продвинет и «пнёт».',
           '4 цифры: ✅ Высокая степень одарённости. Важно развивать таланты — они даны от рода. Идеал: одна 7, одна 8, две 9.',
           '5+ цифр: 🟡 Перегруз. Высокая одарённость, может быть разброс талантов. Важно выбрать направление и фокусироваться.']
  }

  const colsData = {}
  for (const [k, col] of Object.entries(result.columns)) {
    const levels = colLevels[k] || []
    const s = col.sum
    let levelIdx = 0
    if (k === 'c456') {
      if (s === 0) levelIdx = 0
      else if (s === 1) levelIdx = 1
      else if (s === 2) levelIdx = 2
      else if (s === 3) levelIdx = 3
      else if (s === 4) levelIdx = 4
      else levelIdx = 5
    } else {
      if (s <= 4) levelIdx = 0
      else if (s <= 7) levelIdx = 1
      else levelIdx = 2
    }
    colsData[k] = { ...col, level: levels[levelIdx] || '', sum: s }
  }

  // ── Row levels ──────────────────────
  const rowLevels = {
    r147: ['0-3 цифр: ⚠ Цель размыта, сложно ставить и удерживать фокус. Не хватает воли и организованности. Нужна поддержка, учиться доводить дела до конца.',
           '4-6 цифр: ✅ Уверенное движение к целям. Человек умеет ставить задачи и последовательно их решать. Может быть лидером.',
           '7+ цифр: 🔶 Высокая целеустремлённость, но возможна излишняя жёсткость. Может «идти по головам». Важно сохранять гибкость.'],
    r258: ['0-3 цифр: ⚠ Независимость от семьи, слабая привязанность к дому. Важно осознанно выстраивать семейные связи.',
           '4-6 цифр: ✅ Семейные ценности в балансе. Ценит семью, умеет заботиться о близких, сохраняя личное пространство.',
           '7+ цифр: 🔶 Гиперопека. Человек может жертвовать собой ради семьи. Важно соблюдать баланс.'],
    r369: ['0-3 цифр: ⚠ Склонность к переменам. Трудно удерживать один уклад. Важно найти баланс между новизной и стабильностью.',
           '4-6 цифр: ✅ Умеренная стабильность. Золотая середина между консерватизмом и жаждой перемен.',
           '7+ цифр: 🔶 Консервативность, сильная привязанность к привычкам. С трудом принимает изменения.']
  }
  const rowsData = {}
  for (const [k, r] of Object.entries(result.rows)) {
    const levels = rowLevels[k] || []
    const s = r.sum
    const idx = s <= 3 ? 0 : s <= 6 ? 1 : 2
    rowsData[k] = { ...r, level: levels[idx] || '', sum: s }
  }

  // ── Diagonal levels ─────────────────
  const diaLevels = {
    d159: ['0-3 цифр: ⚠ Приземлённость, материальные интересы преобладают. Редко задумывается о смысле жизни.',
           '4-6 цифр: ✅ Духовные интересы в балансе с материальными. Развитая интуиция.',
           '7+ цифр: 🔶 Высокий духовный потенциал, возможен отрыв от реальности.'],
    d357: ['0-3 цифр: ⚠ Спокойный темперамент, сдержанность в проявлении чувств.',
           '4-6 цифр: ✅ Гармоничный темперамент. Хороший баланс эмоциональности и сдержанности.',
           '7+ цифр: 🔶 Высокая эмоциональность, импульсивность. Важно направлять страсть в созидательное русло.']
  }
  const diasData = {}
  for (const [k, d] of Object.entries(result.diagonals)) {
    const levels = diaLevels[k] || []
    const s = d.sum
    const idx = s <= 3 ? 0 : s <= 6 ? 1 : 2
    diasData[k] = { ...d, level: levels[idx] || '', sum: s }
  }

  // ── Money channel (FULL) ──────────
  const mt4 = c[4] || 0, mt5 = c[5] || 0, mt6 = c[6] || 0
  const moneyTotal = mt4 + mt5 + mt6
  const moneyHouse = `🏠 Модель дома: 4 — крыша (сохранение в старости, вложение). 5 — стены (удержание, приумножение). 6 — фундамент (желания, заработок). Без фундамента нельзя построить хороший дом.`
  const moneyEntry = []
  if (mt6 === 1) moneyEntry.push('Одна 6 — трудоголизм. Деньги через усердие, доп. работу.')
  if (mt4 === 1) moneyEntry.push('Одна 4 — телесный вход. Бьюти-сфера, медитации, телесные практики.')
  if (mt5 === 1) moneyEntry.push('Одна 5 — взаимодействие с миром. Торговля, посредники.')
  if (mt6 === 2) moneyEntry.push('66 — мастерство и экспертность. Стать лучшим в одной сфере.')
  if (mt5 === 2) moneyEntry.push('55 — адвокатура, прокуратура, работа с законом, свой бизнес.')
  if (mt4 === 2) moneyEntry.push('44 — целители, ветеринары, телесные практики, остеопатия.')
  if (mt6 === 3) moneyEntry.push('666 — финансовая сфера, консультант, управление финансами.')
  if (mt4 === 3) moneyEntry.push('444 — целительство силой мысли, материализация мыслей.')
  if (mt6 === 4) moneyEntry.push('6666 — управление ресурсами, инвестиции. Богатый род.')
  if (mt4 === 4) moneyEntry.push('4444 — огромный невидимый потенциал, нужен помогатор.')
  if (mt5 === 4) moneyEntry.push('5555 — бизнес, работа с людьми.')
  if (moneyTotal === 0) moneyEntry.push('🔴 Канал пустой — программа тотальной нищеты. Требуется работа с родом.')

  let moneyFull = moneyHouse
  const col6Level = colsData.c456?.level || ''
  if (col6Level) moneyFull += '\n\n📊 Уровень: ' + col6Level
  if (moneyEntry.length) moneyFull += '\n\n🔑 Точки входа:\n' + moneyEntry.map(e => '— ' + e).join('\n')

  // ── Clan flow ───────────────────────
  let clanFlow = null
  let maxDigit = 1
  for (let i = 2; i <= 9; i++) { if (c[i] > c[maxDigit]) maxDigit = i }
  if (c[maxDigit] >= 2 && I.CLAN_FLOWS[maxDigit]) {
    clanFlow = { digit: maxDigit, ...I.CLAN_FLOWS[maxDigit] }
  }

  // ── Cycles ──────────────────────────
  const now = new Date()
  const cy = now.getFullYear()
  // Личный цикл = личный год (день + месяц + год → 1–9), как на карточке
  // «Личный год»; раньше считался от числа пути и расходился с карточкой.
  const personalCycle = personalYearOf(result.input?.day || 1, result.input?.month || 1, cy)
  const genealogicalCycle = rodCycleOf(result.input?.day || 1, result.input?.month || 1, cy)

  // ── Self curses ─────────────────────
  const curses = []
  const numStr = `${nums?.n1 || 0}.${nums?.n2 || 0}`
  for (const [key, desc] of Object.entries(I.SELF_CURSES)) {
    if (numStr.includes(key)) curses.push({ code: key, desc })
  }

  // ── Clan programs ──────────────────
  const clanProgs = []
  if (c[2] === 0 && c[4] === 0 && c[8] === 0) clanProgs.push({ name: 'Уход из Рода', desc: 'Предок был вынужден покинуть родовую семью (пропал без вести, вышел замуж и перестала общаться, инвалиды, больные, преступники, эзотерики). Проявляется в 4 поколении. Сопровождается отсутствием 2,4,8.' })
  if (c[1] >= 2 && c[2] <= 1) clanProgs.push({ name: 'Отказ от себя', desc: 'Жёсткий отказ от предназначения: человек имеет талант к определённой деятельности, но из-за страха или давления социума идёт в родовую профессию, не используя свой дар. Проявляется в 5 поколении.' })
  if (c[4] === 0 && c[5] === 0 && c[8] === 0) clanProgs.push({ name: 'Отказ от любви', desc: 'Блок на серьёзные чувства, боязнь боли и разочарования. Предков заставили вступить в брак без любви. Проявляется в 4–5 поколении.' })
  if (c[4] === 0 || c[5] === 0 || c[6] === 0) clanProgs.push({ name: 'Отказ от денег', desc: 'Предок добровольно отказался от финансового благополучия ради высокой цели (например, крестьянин сдал коров в колхоз). Деньги приходят тяжело и долго не задерживаются.' })
  if (c[2] === 0 && c[8] === 0) clanProgs.push({ name: 'Программа «Уход» (холодность)', desc: 'Предки были разобщены: дедушка имел вторую семью на войне. Холодность передаётся внучкам. Блок на замужество.' })
  if (c[2] <= 1 && c[4] === 0) clanProgs.push({ name: 'Много исключённых в Роду', desc: 'Если кому-то отказано в праве на принадлежность, младшее поколение компенсирует плохим поведением (алкоголь, уход из семьи).' })
  if (c[4] === 0) clanProgs.push({ name: 'Много абортированных детей', desc: 'Проблемы отношений с мамой, закрытое сердце к живущим детям. У мужчин отток денег, у женщин отток энергии.' })
  if (c[1] >= 3 && c[2] >= 2 && c[5] === 0) clanProgs.push({ name: 'Не могу выйти замуж/жениться', desc: 'У женщин: сильный мужской стержень (1111/11111 + 222 + нет 5). У мужчин: страх ответственности (1/11 + 22 + нет 6 + нет 5).' })
  if (c[5] >= 3) clanProgs.push({ name: 'Тотальная нелюбовь', desc: 'Предки жили против своей воли: браки по расчёту, нелюбимая работа. Человеку сколько любви ни дай — всё мало.' })

  // ── Roles ──────────────────────────
  const roles = []
  I.CLAN_ROLES.forEach(r => { try { if (r.check(c)) roles.push(r) } catch {} })

  // ── Stones ──────────────────────────
  const stones = []
  if (c[8] === 0) stones.push('Родонит — помогает выйти на связь с Родом. Открыть знания про семейную историю.')
  if (c[6] === 0) stones.push('Варисцит — проработка кармических проблем, влияющих на отношения с родителями.')
  if (c[8] >= 2) stones.push('Розовый кварц — простить и принять отца и маму, отпустить обиды.')
  if (c[4] >= 2 || c[1] >= 2) stones.push('Горный хрусталь — усилит способности для очищения своего Рода.')
  if (c[1] <= 2 || c[6] <= 1) stones.push('Гранат — физическая сила, уверенность и решительность выдерживать аскезы.')
  if (moneyTotal <= 2 || moneyTotal >= 5) stones.push('Тигровый глаз — активность, успех в поставленной цели, материальное благополучие.')
  if (c[3] >= 2) stones.push('Турмалин — пробуждает творческие силы и скрытые таланты.')
  if (c[7] >= 2) stones.push('Лабрадор — даёт мистическое осознание, развивает ясновидение и яснознание.')
  if (c[5] >= 3) stones.push('Цитрин — камень богатства, благополучия, покровительствует в торговле и бизнесе.')
  if (c[1] >= 3) stones.push('Оникс — талисман лидеров, первооткрывателей, мудрецов.')

  // ── Generation ──────────────────────
  // Программа поколения — по ЧРП, то есть 4-му доп. числу (решение владельца 28.09.2026).
  const genNum = I.GEN_MAP[result.tasks?.rod] || null
  const genProgram = genNum ? I.GENERATION_PROGRAMS[genNum] : null

  return {
    interpretations: {
      digits: digitMeanings,
      soulTask,
      rodTask,
      birthNumber: birthMeaning,
      rows: rowsData,
      columns: colsData,
      diagonals: diasData,
      moneyChannel: {
        total: moneyTotal,
        c4: mt4, c5: mt5, c6: mt6,
        level: colsData.c456?.level || '',
        house: moneyHouse,
        entryPoints: moneyEntry,
        full: moneyFull
      },
      clanFlow,
      personalCycle: { number: personalCycle, meaning: I.PERSONAL_CYCLE[personalCycle] || '' },
      genealogicalCycle: { number: genealogicalCycle, meaning: I.GENEALOGICAL_CYCLE[genealogicalCycle] || '' },
      selfCurses: curses,
      clanPrograms: clanProgs,
      clanRoles: roles,
      stones,
      generationProgram: genProgram ? { generation: genNum, text: genProgram } : null,
      monthTask: I.MONTH_TASKS[result.input?.month] || ''
    }
  }
}

module.exports = { enrich }
